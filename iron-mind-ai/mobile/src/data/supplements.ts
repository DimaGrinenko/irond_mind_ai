export type SupplementCategory =
  | 'protein'       // Протеины
  | 'creatine'      // Креатин
  | 'aminoacid'     // Аминокислоты (BCAA, EAA, глютамин)
  | 'preworkout'    // Предтренировочные (кофеин, цитруллин, бета-аланин)
  | 'recovery'      // Восстановление (магний, ZMA)
  | 'vitamin'       // Витамины (D3, B-комплекс, Mg, Zn)
  | 'omega'         // Жирные кислоты
  | 'gainer'        // Гейнеры
  | 'fatburner'     // Жиросжигатели
  | 'hormonal'      // Гормональные саппорт (DAA, Tribulus)
  | 'joint'         // Суставы (хондроитин, MSM, коллаген)
  | 'chemistry'     // ⚠️ AAS / SARM / PED — образовательная harm-reduction секция
  | 'other';

export type SupplementTiming =
  | 'morning'
  | 'preworkout'
  | 'duringworkout'
  | 'postworkout'
  | 'beforesleep'
  | 'withmeal'
  | 'anytime';

export type Supplement = {
  id: string;
  name: string;
  category: SupplementCategory;
  emoji: string;
  /** Краткое описание что это */
  whatIs: string;
  /** Что делает в теле (физиология) */
  effect: string;
  /** Рекомендованная дозировка */
  dosage: string;
  /** Когда принимать */
  timing: SupplementTiming[];
  /** Длительность приёма / циклирование */
  cycle: string;
  /** Когда полезно (цели) */
  goodFor: string[];
  /** Побочки / противопоказания */
  cautions: string;
  /** Уровень доказательности */
  evidence: 'high' | 'medium' | 'low';
  /** Топ-позиция (1-10), 0 = не в топе */
  topRank: number;
  /** ⚠️ Только для category='chemistry' — расширенная harm-reduction информация */
  sideEffects?: string;
  legality?: string;
  pct?: string;
  labs?: string;
};

