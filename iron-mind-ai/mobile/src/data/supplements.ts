export function topSupplements(limit = 10): Supplement[] {
  return supplements
    .filter((s) => s.topRank > 0)
    .sort((a, b) => a.topRank - b.topRank)
    .slice(0, limit);
}

export function supplementsByCategory(cat: SupplementCategory): Supplement[] {
  return supplements.filter((s) => s.category === cat);
}

export function searchSupplements(q: string): Supplement[] {
  const t = q.trim().toLowerCase();
  if (!t) return supplements;
  return supplements.filter(
    (s) => s.name.toLowerCase().includes(t) || s.whatIs.toLowerCase().includes(t) || s.effect.toLowerCase().includes(t),
  );
}

